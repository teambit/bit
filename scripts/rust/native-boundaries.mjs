#!/usr/bin/env node
// Source census, not a native-coverage score. Review each site before classifying it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const destination = path.join(root, 'docs/rust/native-boundaries.md');
const check = process.argv.includes('--check');
if (process.argv.slice(2).some((arg) => arg !== '--check')) throw new Error('usage: native-boundaries.mjs [--check]');

function files(directory) {
  return fs
    .readdirSync(directory, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name, 'en'))
    .flatMap((entry) => {
      const filename = path.join(directory, entry.name);
      if (entry.isDirectory())
        return ['target', 'node_modules', 'tests', 'fixtures'].includes(entry.name) ? [] : files(filename);
      return /\.(rs|js)$/.test(entry.name) && !/(?:^|_)tests?\.rs$/.test(entry.name) ? [filename] : [];
    });
}

const matchers = [
  ['Decline / optional outcome', /Outcome::Declined|\bdecline\s*\(|\bOk\(None\)/],
  ['Published runtime discovery', /\bdiscovery::|\bNodeCli\b/],
  ['Host calls / construction', /\bHost::|\.(?:call|call_owned)\(/],
  ['Process launch candidates', /\b(?:Command|ProcessCommand)::new\(/],
  ['JavaScript runtime calls', /\b(?:bitRequire|loadHarmony)\(/],
];
const rows = [];
for (const filename of files(path.join(root, 'native'))) {
  if (!filename.includes(`${path.sep}src${path.sep}`)) continue;
  const relative = path.relative(root, filename).split(path.sep).join('/');
  const lines = fs.readFileSync(filename, 'utf8').split('\n');
  const matches = matchers.map(([, expression]) =>
    lines.flatMap((line, index) => (!line.trimStart().startsWith('//') && expression.test(line) ? [index + 1] : []))
  );
  if (!matches.some((positions) => positions.length)) continue;
  const columns = matches.map(
    (positions) => positions.map((line) => `[${line}](../../${relative}#L${line})`).join(', ') || '—'
  );
  rows.push(`| [${relative}](../../${relative}) | ${columns.join(' | ')} |`);
}
const output = `# Native runtime boundary census

Generated by \`node scripts/rust/native-boundaries.mjs\`; verify with \`--check\`.

This is a **review queue, not an implementation percentage**. Lexical matches include
ordinary optional lookups, Rust trait calls and legitimate Git/tool processes. They
also include invalid-input guards. Conversely, indirect helpers and dynamic JavaScript
calls require manual review. Tests are excluded by directory/file convention; inline
test modules may appear. A missing match never proves a command is independent of Node.

Review this alongside [command coverage](../rust-cli.md), the public command
registrations, and [the completion plan](https://github.com/zkochan/bit/issues/395).
For each supported command/mode, prove both that the dispatcher does not delegate
and that no published-Bit runtime adapter executes. Track third-party tool processes
separately. Yarn support is excluded from the completion plan.

| Source | ${matchers.map(([label]) => label).join(' | ')} |
| --- | ${matchers.map(() => '---').join(' | ')} |
${rows.join('\n')}
`;
if (check) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) {
    console.error('Native boundary census is stale. Run node scripts/rust/native-boundaries.mjs.');
    process.exitCode = 1;
  }
} else fs.writeFileSync(destination, output);
