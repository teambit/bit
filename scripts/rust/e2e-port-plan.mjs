#!/usr/bin/env node
// Lists every e2e case (`it(...)` under `e2e/`) in the generated part of
// native/plans/TEST_PORTING.md, keeping the state and the note of the cases already listed.
//
//   node scripts/rust/e2e-port-plan.mjs          rewrite the plan
//   node scripts/rust/e2e-port-plan.mjs --check  fail when the plan is out of date
//
// A case is `- [ ] \`<file>:<line>\` <describe> › … › <it>`, optionally followed by
// ` — <note>`. `[x]` marks a ported case, `[-]` one that will not be ported (the note says why).
// Cases are matched by file and title, so a moved case keeps its state; a case whose title
// changed is listed again as new, and the script names the dropped one.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const PLAN = path.join(ROOT, 'native/plans/TEST_PORTING.md');
const BEGIN = '<!-- e2e-port-plan:begin (generated by scripts/rust/e2e-port-plan.mjs; edit only the boxes and notes) -->';
const END = '<!-- e2e-port-plan:end -->';
const SEPARATOR = ' › ';
const NOTE = ' — ';

function e2eFiles(dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) return entry.name === 'fixtures' ? [] : e2eFiles(full);
      return /\.e2e(\.\d+)?\.ts$/.test(entry.name) ? [full] : [];
    })
    .sort();
}

/** The index after the string, comment or template literal starting at `index`, else `index`. */
function skipLiteral(source, index) {
  const char = source[index];
  if (char === '/' && source[index + 1] === '/') {
    const end = source.indexOf('\n', index);
    return end === -1 ? source.length : end;
  }
  if (char === '/' && source[index + 1] === '*') {
    return source.indexOf('*/', index + 2) + 2;
  }
  if (char !== '"' && char !== "'" && char !== '`') return index;
  let cursor = index + 1;
  while (cursor < source.length && source[cursor] !== char) {
    if (source[cursor] === '\\') cursor += 1;
    else if (char === '`' && source[cursor] === '$' && source[cursor + 1] === '{') {
      cursor = closing(source, cursor + 1, '{', '}');
    }
    cursor += 1;
  }
  return cursor + 1;
}

/** The index of the bracket closing the one at `open`. */
function closing(source, open, opening, closer) {
  let depth = 0;
  let cursor = open;
  while (cursor < source.length) {
    const skipped = skipLiteral(source, cursor);
    if (skipped !== cursor) {
      cursor = skipped;
      continue;
    }
    if (source[cursor] === opening) depth += 1;
    else if (source[cursor] === closer) {
      depth -= 1;
      if (depth === 0) return cursor;
    }
    cursor += 1;
  }
  return source.length;
}

/** The first argument of the call whose `(` is at `open`, when it is a literal title. */
function title(source, open) {
  let cursor = open + 1;
  while (/\s/.test(source[cursor])) cursor += 1;
  const quote = source[cursor];
  if (quote !== '"' && quote !== "'" && quote !== '`') return undefined;
  const end = skipLiteral(source, cursor);
  return source
    .slice(cursor + 1, end - 1)
    .replace(/\\(['"`])/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Every `it` of `file` with its line and the titles of the `describe`s around it. */
function cases(file) {
  const source = fs.readFileSync(file, 'utf8');
  const call = /\b(describe|context|it)(\.only|\.skip)?\s*\(/y;
  const found = [];
  const scopes = [];
  let cursor = 0;
  while (cursor < source.length) {
    const skipped = skipLiteral(source, cursor);
    if (skipped !== cursor) {
      cursor = skipped;
      continue;
    }
    call.lastIndex = cursor;
    const match = /[\w$.]/.test(source[cursor - 1] ?? '') ? null : call.exec(source);
    if (!match) {
      cursor += 1;
      continue;
    }
    const open = cursor + match[0].length - 1;
    while (scopes.length && scopes.at(-1).end < cursor) scopes.pop();
    const name = title(source, open) ?? '(dynamic title)';
    const line = source.slice(0, cursor).split('\n').length;
    if (match[1] === 'it') {
      found.push({ line, titles: [...scopes.map((scope) => scope.name), name] });
    } else {
      scopes.push({ name, end: closing(source, open, '(', ')') });
    }
    cursor = open + 1;
  }
  return found;
}

function discoverCases() {
  const byFile = new Map();
  for (const file of e2eFiles(path.join(ROOT, 'e2e'))) {
    const relative = path.relative(ROOT, file).split(path.sep).join('/');
    byFile.set(
      relative,
      cases(file).map(({ line, titles }) => ({ line, text: titles.join(SEPARATOR) }))
    );
  }
  return byFile;
}

function generate(discovered, previous) {
  const sections = [];
  const used = new Set();
  for (const [relative, fileCases] of discovered) {
    const seen = new Map();
    const lines = fileCases.map(({ line, text }) => {
      const occurrence = (seen.get(text) ?? 0) + 1;
      seen.set(text, occurrence);
      const key = `${relative}\0${text}\0${occurrence}`;
      used.add(key);
      const old = previous.get(key);
      return `- [${old?.state ?? ' '}] \`${relative}:${line}\` ${text}${old?.note ? NOTE + old.note : ''}`;
    });
    if (lines.length) sections.push(`### \`${relative}\`\n\n${lines.join('\n')}`);
  }
  const dropped = [...previous].filter(([key, item]) => !used.has(key) && item.state !== ' ');
  return { body: sections.join('\n\n'), dropped };
}

/** The listed cases by file, title and occurrence, with their state and note. */
function parse(generated, discovered) {
  const items = new Map();
  const seen = new Map();
  for (const line of generated.split('\n')) {
    const match = /^- \[(.)\] `([^`]+):\d+` (.*)$/.exec(line);
    if (!match) continue;
    const [, state, file, rest] = match;
    const known = (discovered.get(file) ?? [])
      .map((item) => item.text)
      .find((candidate) => rest === candidate || rest.startsWith(candidate + NOTE));
    let text;
    let note;
    if (known !== undefined) {
      text = known;
      note = rest === known ? '' : rest.slice(known.length + NOTE.length);
    } else {
      const noteAt = rest.indexOf(NOTE);
      text = noteAt === -1 ? rest : rest.slice(0, noteAt);
      note = noteAt === -1 ? '' : rest.slice(noteAt + NOTE.length);
    }
    const occurrence = (seen.get(`${file}\0${text}`) ?? 0) + 1;
    seen.set(`${file}\0${text}`, occurrence);
    items.set(`${file}\0${text}\0${occurrence}`, { state, note, text: `${file}: ${text}` });
  }
  return items;
}

const plan = fs.readFileSync(PLAN, 'utf8');
const begin = plan.indexOf(BEGIN);
const end = plan.indexOf(END);
if (begin === -1 || end === -1) {
  console.error(`${PLAN} lacks the generated markers`);
  process.exit(1);
}
const discovered = discoverCases();
const { body, dropped } = generate(discovered, parse(plan.slice(begin + BEGIN.length, end), discovered));
const updated = `${plan.slice(0, begin)}${BEGIN}\n\n${body}\n\n${plan.slice(end)}`;
for (const [, item] of dropped) {
  console.error(`no longer in e2e/, was [${item.state}]: ${item.text}`);
}
if (process.argv.includes('--check')) {
  if (updated !== plan) {
    console.error('native/plans/TEST_PORTING.md is out of date: run node scripts/rust/e2e-port-plan.mjs');
    process.exit(1);
  }
} else {
  fs.writeFileSync(PLAN, updated);
}
