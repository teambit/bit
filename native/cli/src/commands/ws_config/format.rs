//! Output formatting for `bit ws-config write`.

use super::{WriteOptions, clean::format_clean_output};
use crate::commands::{color::Chalk, workspace_command::format::Formatter};
use serde::Serialize;
use std::path::Path;

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub(super) struct WriteConfigFilesResult {
    pub ws_dir: String,
    pub clean_results: Vec<String>,
    pub write_results: WriteResults,
}

#[derive(Debug, Default, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub(super) struct WriteResults {
    pub writers_result: Vec<OneConfigWriterIdResult>,
    pub total_written_files: usize,
    pub total_real_config_files: usize,
    pub total_extending_config_files: usize,
    pub skipped_paths: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub(super) struct OneConfigWriterIdResult {
    pub writer_id: String,
    pub total_written_files: usize,
    pub real_config_files: Vec<EnvsWrittenRealConfigFile>,
    pub total_real_config_files: usize,
    pub extending_config_files: Vec<EnvsWrittenExtendingConfigFile>,
    pub total_extending_config_files: usize,
    pub skipped_paths: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub(super) struct EnvsWrittenRealConfigFile {
    pub env_ids: Vec<String>,
    pub written_real_config_file: WrittenConfigFile,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub(super) struct WrittenConfigFile {
    pub name: String,
    pub hash: String,
    pub file_path: String,
    pub content: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub(super) struct EnvsWrittenExtendingConfigFile {
    pub env_ids: Vec<String>,
    pub extending_config_file: WrittenExtendingConfigFile,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub(super) struct WrittenExtendingConfigFile {
    pub name: String,
    pub hash: String,
    pub content: String,
    pub extending_target: WrittenConfigFile,
    pub file_paths: Vec<String>,
}

const SUMMARY_INTRO: &str = "bit writes configuration files in different nested locations in your workspace to meet the configuration needs of different components.";
const SUMMARY_CLEAN: &str = "IDE is now in-sync with component configuration";
const SUMMARY_SKIPPED: &str = "IDE is in-sync with component configuration, except for the files above, which bit left as they are";
const SKIPPED_DESC: &str = "these files already exist and were not generated by bit, so they were left untouched.\nto have bit write them, delete them first or run \"bit ws-config write --force\".";

pub(super) fn format_write_output(
    result: &WriteConfigFilesResult,
    opts: &WriteOptions,
    chalk: Chalk,
) -> String {
    let is_dry = opts.dry_run.is_dry();
    let ws_dir = Path::new(&result.ws_dir);
    if opts.verbose {
        return format_verbose(result, ws_dir, is_dry, chalk);
    }
    let clean_out = (!result.clean_results.is_empty()).then(|| {
        format_clean_output(&result.clean_results, is_dry, chalk)
    });
    let write_out = format_non_verbose_results(&result.write_results, ws_dir, is_dry, chalk);
    let combined = match clean_out {
        Some(clean) => format!("{clean}\n{write_out}"),
        None => write_out,
    };
    let skipped = format_skipped(&result.write_results.skipped_paths, ws_dir, chalk);
    let summary = write_summary(&result.write_results.skipped_paths);
    Formatter::join(&[combined, skipped, summary])
}

fn format_verbose(
    result: &WriteConfigFilesResult,
    ws_dir: &Path,
    is_dry: bool,
    chalk: Chalk,
) -> String {
    let clean_out = format_clean_output(&result.clean_results, is_dry, chalk);
    let write_out = format_verbose_results(&result.write_results, ws_dir, is_dry, chalk);
    let skipped = format_skipped(&result.write_results.skipped_paths, ws_dir, chalk);
    let summary = write_summary(&result.write_results.skipped_paths);
    Formatter::join(&[format!("{clean_out}\n{write_out}"), skipped, summary])
}

fn format_non_verbose_results(
    write_results: &WriteResults,
    ws_dir: &Path,
    is_dry: bool,
    chalk: Chalk,
) -> String {
    let total = write_results.total_extending_config_files;
    let title = if is_dry {
        chalk.green(&format!("{total} files will be written"))
    } else {
        chalk.green(&format!("{total} config files added to workspace"))
    };
    let writers = write_results.writers_result
        .iter()
        .map(|writer| format_one_writer_short(writer, ws_dir, chalk))
        .collect::<Vec<_>>()
        .join("\n\n");
    format!("{title}\n{writers}")
}

fn format_one_writer_short(
    writer: &OneConfigWriterIdResult,
    ws_dir: &Path,
    chalk: Chalk,
) -> String {
    let title = chalk_blue(
        chalk,
        &format!(
            "{} {} configurations added",
            writer.total_extending_config_files,
            chalk.bold(&writer.writer_id),
        ),
    );
    let groups = writer.extending_config_files
        .iter()
        .map(|ext| {
            ext.extending_config_file.file_paths
                .iter()
                .map(|file_path| format!("  {}", rel_display(ws_dir, file_path)))
                .collect::<Vec<_>>()
                .join("\n")
        })
        .collect::<Vec<_>>()
        .join("\n");
    format!("{title}\n{groups}")
}

fn format_verbose_results(
    write_results: &WriteResults,
    ws_dir: &Path,
    is_dry: bool,
    chalk: Chalk,
) -> String {
    let total = write_results.total_written_files;
    let title = if is_dry {
        chalk.green(&format!("{total} files will be written"))
    } else {
        chalk.green(&format!("{total} config files added to workspace"))
    };
    let writers = write_results.writers_result
        .iter()
        .map(|writer| format_one_writer_verbose(writer, ws_dir, chalk))
        .collect::<Vec<_>>()
        .join("\n\n");
    format!("{title}\n{writers}")
}

fn format_one_writer_verbose(
    writer: &OneConfigWriterIdResult,
    ws_dir: &Path,
    chalk: Chalk,
) -> String {
    let title = chalk.cyan(&format!(
        "  The following paths are according to writer {}",
        chalk.bold(&writer.writer_id),
    ));
    let real_title = chalk_magenta(chalk, "  Real config files");
    let real_groups = writer.real_config_files
        .iter()
        .map(|real| format_real_group(real, ws_dir, chalk))
        .collect::<Vec<_>>()
        .join("\n\n");
    let ext_title = chalk_magenta(chalk, "  Extending config files");
    let ext_groups = writer.extending_config_files
        .iter()
        .map(|ext| format_extending_group(ext, ws_dir, chalk))
        .collect::<Vec<_>>()
        .join("\n\n");
    format!("{title}\n{real_title}\n{real_groups}\n\n{ext_title}\n{ext_groups}")
}

fn chalk_blue(chalk: Chalk, text: &str) -> String {
    if chalk.enabled() { format!("\u{1b}[34m{text}\u{1b}[39m") } else { text.to_owned() }
}

fn chalk_magenta(chalk: Chalk, text: &str) -> String {
    if chalk.enabled() { format!("\u{1b}[35m{text}\u{1b}[39m") } else { text.to_owned() }
}

fn format_real_group(real: &EnvsWrittenRealConfigFile, ws_dir: &Path, chalk: Chalk) -> String {
    let env_list = chalk.bold(&real.env_ids.join(", "));
    let rel_path = rel_display(ws_dir, &real.written_real_config_file.file_path);
    format!("    The following paths are according to env(s) {env_list}\n      {rel_path}")
}

fn format_extending_group(
    ext: &EnvsWrittenExtendingConfigFile,
    ws_dir: &Path,
    chalk: Chalk,
) -> String {
    let env_list = chalk.bold(&ext.env_ids.join(", "));
    let target_rel = rel_display(ws_dir, &ext.extending_config_file.extending_target.file_path);
    let paths = ext.extending_config_file.file_paths
        .iter()
        .map(|file_path| format!("  {} --> {target_rel}", rel_display(ws_dir, file_path)))
        .collect::<Vec<_>>()
        .join("\n    ");
    format!("    The following paths are according to env(s) {env_list}\n    {paths}")
}

fn format_skipped(skipped_paths: &[String], ws_dir: &Path, chalk: Chalk) -> String {
    if skipped_paths.is_empty() {
        return String::new();
    }
    let formatter = Formatter::new(chalk);
    let items: Vec<String> = skipped_paths
        .iter()
        .map(|file_path| formatter.item(&rel_display(ws_dir, file_path)))
        .collect();
    let title = format!("{} config files not overridden", formatter.warn_symbol());
    formatter.section(&title, SKIPPED_DESC, &items)
}

fn write_summary(skipped_paths: &[String]) -> String {
    let second = if skipped_paths.is_empty() { SUMMARY_CLEAN } else { SUMMARY_SKIPPED };
    format!("{SUMMARY_INTRO}\n{second}")
}

fn rel_display(ws_dir: &Path, full_path: &str) -> String {
    let full_path = full_path.trim();
    Path::new(full_path)
        .strip_prefix(ws_dir)
        .map_or_else(|_| full_path.to_owned(), |rel| rel.to_string_lossy().replace('\\', "/"))
}

pub(super) fn strip_dry_run_contents(write_results: &mut WriteResults) {
    for writer in &mut write_results.writers_result {
        for real in &mut writer.real_config_files {
            real.written_real_config_file.content.clear();
        }
        for ext in &mut writer.extending_config_files {
            ext.extending_config_file.content.clear();
            ext.extending_config_file.extending_target.content.clear();
        }
    }
}

pub(super) fn summarize_writers(writers_result: Vec<OneConfigWriterIdResult>) -> WriteResults {
    let total_real: usize = writers_result
        .iter()
        .map(|wr| wr.total_real_config_files)
        .sum();
    let total_extending: usize = writers_result
        .iter()
        .map(|wr| wr.total_extending_config_files)
        .sum();
    let skipped_paths = writers_result
        .iter()
        .flat_map(|wr| wr.skipped_paths.iter().cloned())
        .collect();
    WriteResults {
        writers_result,
        total_written_files: total_real + total_extending,
        total_real_config_files: total_real,
        total_extending_config_files: total_extending,
        skipped_paths,
    }
}

pub(super) fn finish_one_writer(
    writer_id: &str,
    env_ids: &[String],
    real_config_files: Vec<EnvsWrittenRealConfigFile>,
    extending_config_file: WrittenExtendingConfigFile,
    skipped_paths: Vec<String>,
) -> OneConfigWriterIdResult {
    let total_real = real_config_files.len();
    let total_extending = extending_config_file.file_paths.len();
    OneConfigWriterIdResult {
        writer_id: writer_id.to_owned(),
        total_written_files: total_real + total_extending,
        real_config_files,
        total_real_config_files: total_real,
        extending_config_files: vec![EnvsWrittenExtendingConfigFile {
            env_ids: env_ids.to_vec(),
            extending_config_file,
        }],
        total_extending_config_files: total_extending,
        skipped_paths,
    }
}
