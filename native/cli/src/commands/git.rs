pub const COMMAND: Command = Command { name: "git", aliases: &[], run };

const BITMAP_HEADER: &str = "/* THIS IS A BIT-AUTO-GENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY. */\n\n/**\n * The Bitmap file is an auto generated file used by Bit to track all your Bit components. It maps the component to a folder in your file system.\n * This file should be committed to VCS(version control).\n * Components are listed using their component ID (https://bit.dev/reference/components/component-id).\n * If you want to delete components you can use the \"bit remove <component-id>\" command.\n * See the docs (https://bit.dev/reference/components/removing-components) for more information, or use \"bit remove --help\".\n */\n\n";
const GIT_NAME_KEY: &str = "merge.bitmap-driver.name";
const GIT_DRIVER_KEY: &str = "merge.bitmap-driver.driver";
const GIT_NAME_VALUE: &str = "A custom merge driver used to resolve conflicts in .bitmap files";
const GIT_DRIVER_VALUE: &str = "bd git merge-bitmaps %O %A %B";
const GIT_ATTRIBUTES_LINE: &str = ".bitmap merge=bitmap-driver";

#[derive(Debug, Clone, PartialEq, Eq)]
enum Parsed {
    MergeBitmaps { current: String, other: String },
    SetMergeDriver { global: bool },
    Unrecognized(String),
}

fn run(args: &[OsString]) -> io::Result<Outcome> {
    let Some(parsed) = parse_args(args) else {
        return Ok(Outcome::Declined("arguments outside the native `git` grammar".to_owned()));
    };
    let chalk = Chalk::detect(args);
    match parsed {
        Parsed::MergeBitmaps { current, other } => run_merge_bitmaps(args, &current, &other, chalk),
        Parsed::SetMergeDriver { global } => run_set_merge_driver(args, global, chalk),
        Parsed::Unrecognized(sub) => run_unrecognized(args, &sub, chalk),
    }
}

fn parse_args(args: &[OsString]) -> Option<Parsed> {
    let tokens = args
        .iter()
        .skip(1)
        .map(|arg| arg.to_str())
        .collect::<Option<Vec<_>>>()?
        .into_iter()
        .filter(|token| *token != "--no-color")
        .collect::<Vec<_>>();
    let (&sub, rest) = tokens.split_first()?;
    if sub.is_empty() || sub.starts_with('-') {
        return None;
    }
    match sub {
        "merge-bitmaps" => parse_merge_bitmaps(rest),
        "set-merge-driver" | "smd" => parse_set_merge_driver(rest),
        _ if rest.is_empty() => Some(Parsed::Unrecognized(sub.to_owned())),
        _ => None,
    }
}

fn parse_merge_bitmaps(rest: &[&str]) -> Option<Parsed> {
    let [ancestor, current, other] = rest else {
        return None;
    };
    if [ancestor, current, other]
        .iter()
        .any(|token| token.is_empty() || token.starts_with('-'))
    {
        return None;
    }
    Some(Parsed::MergeBitmaps { current: (*current).to_owned(), other: (*other).to_owned() })
}

fn parse_set_merge_driver(rest: &[&str]) -> Option<Parsed> {
    let mut global = false;
    for &token in rest {
        match token {
            "-g" | "--global" | "--global=true" => global = true,
            "--global=false" => global = false,
            _ => return None,
        }
    }
    Some(Parsed::SetMergeDriver { global })
}

fn run_merge_bitmaps(
    args: &[OsString],
    current: &str,
    other: &str,
    chalk: Chalk,
) -> io::Result<Outcome> {
    let Some(root) = workspace::root(&env::current_dir()?) else {
        return Ok(Outcome::Declined("merge-bitmaps requires a workspace".to_owned()));
    };
    let strategy = match read_merge_strategy(&root) {
        Ok(strategy) => strategy,
        Err(error) => return Ok(Outcome::Declined(error.to_string())),
    };
    let current_text = match fs::read_to_string(current) {
        Ok(text) => strip_bom(&text).to_owned(),
        Err(error) => return Ok(Outcome::Declined(error.to_string())),
    };
    let other_text = match fs::read_to_string(other) {
        Ok(text) => strip_bom(&text).to_owned(),
        Err(error) => return Ok(Outcome::Declined(error.to_string())),
    };
    if env::var_os("CI").is_some_and(|val| !val.is_empty())
        && merge_bitmap_contents(&current_text, &other_text, &strategy).is_err()
    {
        return Ok(Outcome::Declined("CI merge-bitmaps error stack".to_owned()));
    }
    workspace_command::execute_then(&root, args, "merge-bitmaps", |_output| {
        let merged = merge_bitmap_contents(&current_text, &other_text, &strategy)?;
        if let Some(parent) = Path::new(current)
            .parent()
            .filter(|parent| !parent.as_os_str().is_empty())
        {
            fs::create_dir_all(parent)?;
        }
        fs::write(current, merged)?;
        let data = Formatter::new(chalk).success_summary("bitmap files merged successfully");
        Ok(Report { data, code: 0, details: None })
    })
}

fn read_merge_strategy(root: &Path) -> io::Result<String> {
    let bytes = fs::read(root.join("workspace.jsonc"))?;
    let parsed = bit_object_import::parse_jsonc(&bytes)?;
    let rows = parsed.as_object().ok_or_else(|| io::Error::other("workspace.jsonc object"))?;
    let key = rows
        .keys()
        .find(|key| key.split('@').next() == Some("teambit.git/git"))
        .map_or("teambit.git/git", String::as_str);
    Ok(parsed[key]["mergeStrategy"]
        .as_str()
        .filter(|val| !val.is_empty())
        .unwrap_or("manual")
        .to_owned())
}

fn strip_bom(text: &str) -> &str {
    text.strip_prefix('\u{feff}').unwrap_or(text)
}

fn merge_bitmap_contents(current: &str, other: &str, strategy: &str) -> io::Result<String> {
    let parsed = bit_object_import::parse_jsonc(current.as_bytes())?;
    let parsed_other = bit_object_import::parse_jsonc(other.as_bytes())?;
    let cur_obj = parsed.as_object().ok_or_else(|| io::Error::other("current bitmap object"))?;
    let other_obj =
        parsed_other.as_object().ok_or_else(|| io::Error::other("other bitmap object"))?;
    let merged = combine_bitmap_objects(cur_obj, other_obj, strategy)?;
    let mut keys = merged
        .keys()
        .filter(|key| *key != "$schema-version")
        .cloned()
        .collect::<Vec<_>>();
    keys.sort_by(|left, right| left.encode_utf16().cmp(right.encode_utf16()));
    let mut sorted = Map::with_capacity(merged.len());
    for key in keys {
        if let Some(val) = merged.get(&key) {
            sorted.insert(key, val.clone());
        }
    }
    if let Some(schema) = cur_obj
        .get("$schema-version")
        .filter(|val| !val.is_null())
    {
        sorted.insert("$schema-version".to_owned(), schema.clone());
    }
    format_bitmap_object(&sorted)
}

fn combine_bitmap_objects(
    cur_obj: &Map<String, Value>,
    other_obj: &Map<String, Value>,
    strategy: &str,
) -> io::Result<Map<String, Value>> {
    match strategy {
        "ours" => Ok(merge_two_maps(other_obj, cur_obj)),
        "theirs" => Ok(merge_two_maps(cur_obj, other_obj)),
        _ => {
            for (key, cur_val) in cur_obj {
                if let Some(other_val) = other_obj.get(key)
                    && cur_val != other_val
                {
                    return Err(io::Error::other(
                        r#"conflict merging Bitmap, you need to resolve the conflict manually or choose "ours" or "theirs" strategy"#,
                    ));
                }
            }
            Ok(merge_two_maps(other_obj, cur_obj))
        }
    }
}

fn merge_two_maps(first: &Map<String, Value>, second: &Map<String, Value>) -> Map<String, Value> {
    let mut merged = first.clone();
    for (key, value) in second {
        merged.insert(key.clone(), value.clone());
    }
    merged
}

fn format_bitmap_object(sorted: &Map<String, Value>) -> io::Result<String> {
    let mut buf = Vec::new();
    let mut serializer =
        serde_json::Serializer::with_formatter(&mut buf, PrettyFormatter::with_indent(b"    "));
    Value::Object(sorted.clone()).serialize(&mut serializer).map_err(io::Error::other)?;
    let body = String::from_utf8(buf).map_err(io::Error::other)?;
    Ok(format!("{BITMAP_HEADER}{body}"))
}

fn run_set_merge_driver(args: &[OsString], global: bool, chalk: Chalk) -> io::Result<Outcome> {
    let cwd = env::current_dir()?;
    if !global && !cwd.join(".git").exists() {
        if env::var_os("CI").is_some_and(|val| !val.is_empty()) {
            return Ok(Outcome::Declined("CI set-merge-driver error stack".to_owned()));
        }
        let history = workspace::root(&cwd).map(|root| History::start(&root, args));
        let output = workspace_command::loader_output(chalk, false);
        output.restart(r#"running command "set-merge-driver"..."#);
        output.stop();
        if let Some(history) = history {
            history.end(false);
        }
        eprintln!("{}", chalk.red("This is not a git repository"));
        return Ok(Outcome::Exit(ExitCode::FAILURE));
    }
    let history = workspace::root(&cwd).map(|root| History::start(&root, args));
    let output = workspace_command::loader_output(chalk, false);
    output.restart(r#"running command "set-merge-driver"..."#);
    if let Err(error) = apply_git_merge_driver(&cwd, global) {
        output.stop();
        if let Some(history) = history {
            history.end(false);
        }
        return Ok(Outcome::Declined(error.to_string()));
    }
    output.stop();
    let summary = Formatter::new(chalk).success_summary("git merge driver was set");
    writeln!(io::stdout(), "{summary}")?;
    if let Some(history) = history {
        history.end(true);
    }
    Ok(Outcome::Exit(ExitCode::SUCCESS))
}

fn apply_git_merge_driver(cwd: &Path, global: bool) -> io::Result<()> {
    let scope_flag = if global { "--global" } else { "--local" };
    if git_config_get(cwd, scope_flag, GIT_NAME_KEY).is_none() {
        git_config_set(cwd, scope_flag, GIT_NAME_KEY, GIT_NAME_VALUE)?;
        git_config_set(cwd, scope_flag, GIT_DRIVER_KEY, GIT_DRIVER_VALUE)?;
    }
    let attr_path = resolve_attributes_path(cwd, scope_flag, global);
    if attr_path.exists() {
        let content = fs::read_to_string(&attr_path)?;
        if content.contains(GIT_ATTRIBUTES_LINE) {
            return Ok(());
        }
        let mut file = OpenOptions::new().append(true).open(&attr_path)?;
        write!(file, "\n{GIT_ATTRIBUTES_LINE}")
    } else {
        fs::write(&attr_path, GIT_ATTRIBUTES_LINE)
    }
}

fn resolve_attributes_path(cwd: &Path, scope_flag: &str, global: bool) -> PathBuf {
    if let Some(configured) = git_config_get(cwd, scope_flag, "core.attributesFile") {
        return PathBuf::from(configured);
    }
    if !global {
        return cwd.join(".gitattributes");
    }
    if let Some(xdg) = env::var_os("XDG_CONFIG_HOME").filter(|val| !val.is_empty()) {
        return PathBuf::from(xdg).join("git").join("attributes");
    }
    workspace_command::home()
        .join(".config")
        .join("git")
        .join("attributes")
}

fn git_config_get(cwd: &Path, scope_flag: &str, key: &str) -> Option<String> {
    let output = ProcessCommand::new("git")
        .current_dir(cwd)
        .args(["config", scope_flag, "--get", key])
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let value = String::from_utf8_lossy(&output.stdout).trim().to_owned();
    (!value.is_empty()).then_some(value)
}

fn git_config_set(cwd: &Path, scope_flag: &str, key: &str, value: &str) -> io::Result<()> {
    let status = ProcessCommand::new("git")
        .current_dir(cwd)
        .args(["config", scope_flag, key, value])
        .status()?;
    if status.success() {
        Ok(())
    } else {
        Err(io::Error::other(format!("git config {scope_flag} {key} failed")))
    }
}

fn run_unrecognized(args: &[OsString], sub: &str, chalk: Chalk) -> io::Result<Outcome> {
    let history = workspace::root(&env::current_dir()?).map(|root| History::start(&root, args));
    let output = workspace_command::loader_output(chalk, false);
    output.restart(r#"running command "git"..."#);
    output.stop();
    writeln!(io::stdout(), "{}", format_unrecognized(sub, chalk))?;
    if let Some(history) = history {
        history.end(true);
    }
    Ok(Outcome::Exit(ExitCode::SUCCESS))
}

fn format_unrecognized(sub: &str, chalk: Chalk) -> String {
    chalk.red(&format!(
        r#""{sub}" is not a subcommand of "git", please run "bit git --help" to list the subcommands"#,
    ))
}
