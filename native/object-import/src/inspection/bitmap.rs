use super::invalid;
use crate::js_json::{self, Value as Js};
use serde_json::{Map, Value};
use std::io;

const PREFIX: &str = "/* THIS IS A BIT-AUTO-GENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY. */\n\n/**\n * The Bitmap file is an auto generated file used by Bit to track all your Bit components. It maps the component to a folder in your file system.\n * This file should be committed to VCS(version control).\n * Components are listed using their component ID (https://bit.dev/reference/components/component-id).\n * If you want to delete components you can use the \"bit remove <component-id>\" command.\n * See the docs (https://bit.dev/reference/components/removing-components) for more information, or use \"bit remove --help\".\n */\n\n";
pub(super) fn normalize(bytes: &[u8]) -> io::Result<Vec<u8>> {
    let mut value = crate::recovery::jsonc::parse(bytes)?;
    if !truthy(&value) {
        return Ok(bytes.to_vec());
    }
    let map = value.as_object_mut().ok_or_else(|| invalid("inspection bitmap object required"))?;
    map.shift_remove("_bit_lane");
    map.shift_remove("$schema-version");
    let keys = map.keys().cloned().collect::<Vec<_>>();
    for key in keys {
        if normalize_entry(map.get_mut(&key).expect("collected existing key"))? {
            map.shift_remove(&key);
        }
    }
    let mut output = PREFIX.as_bytes().to_vec();
    output.extend(js_json::stringify_indented(&ast(&value)?, 4)?);
    Ok(output)
}
fn removed(entry: &Map<String, Value>) -> bool {
    entry.get("isAvailableOnCurrentLane") == Some(&Value::Bool(false))
        || entry
            .get("config")
            .and_then(|config| config.get("teambit.component/remove"))
            .is_some_and(|remove| {
                remove.as_str() != Some("-") && remove.get("removed").is_some_and(truthy)
            })
}
fn scope(entry: &mut Map<String, Value>) {
    if entry.contains_key("scope") || entry.contains_key("defaultScope") {
        let scope = entry
            .get("scope")
            .filter(|value| truthy(value))
            .or_else(|| entry.get("defaultScope").filter(|value| truthy(value)))
            .cloned()
            .unwrap_or_else(|| Value::String(String::new()));
        entry.insert("scope".into(), scope);
        entry.shift_remove("defaultScope");
    }
}
fn truthy(value: &Value) -> bool {
    match value {
        Value::Null => false,
        Value::Bool(value) => *value,
        Value::String(value) => !value.is_empty(),
        Value::Number(value) => value.as_f64() != Some(0.0),
        _ => true,
    }
}
fn ast(value: &Value) -> io::Result<Js> {
    Ok(match value {
        Value::Null => Js::Null,
        Value::Bool(value) => Js::Boolean(*value),
        Value::String(value) => Js::String(value.encode_utf16().collect()),
        Value::Number(value) => Js::Number(format!(
            "{:016x}",
            value
                .as_f64()
                .ok_or_else(|| invalid("bitmap number"))?
                .to_bits(),
        )),
        Value::Array(values) => Js::Array(
            values
                .iter()
                .map(ast)
                .collect::<io::Result<_>>()?,
        ),
        Value::Object(values) => Js::Object(
            values
                .iter()
                .map(|(key, value)| Ok((key.encode_utf16().collect(), ast(value)?)))
                .collect::<io::Result<_>>()?,
        ),
    })
}

fn normalize_entry(value: &mut Value) -> io::Result<bool> {
    if value.is_array() {
        return Err(invalid("inspection bitmap array entry unsupported"));
    }
    let Some(entry) = value.as_object_mut() else {
        return Ok(false);
    };
    if removed(entry) {
        return Ok(true);
    }
    entry.shift_remove("isAvailableOnCurrentLane");
    entry.shift_remove("onLanesOnly");
    if entry.contains_key("version") {
        entry.insert("version".into(), Value::String(String::new()));
    }
    scope(entry);
    entry.shift_remove("config");
    entry.shift_remove("nextVersion");
    Ok(false)
}
